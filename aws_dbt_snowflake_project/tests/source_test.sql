-- Singular test on the raw (bronze) layer.
-- A singular test PASSES when it returns zero rows and WARNS when it returns any rows.
-- Each returned row is one problem: which rule failed (CHECK_NAME) and which record (RECORD_ID).
-- All rules are combined with UNION ALL so Snowflake only runs ONE small query (cheap for a free trial).
--
-- To test your real sources instead, swap ref('bronze_bookings') for source('<source_name>', '<table>').

WITH bookings AS (
    SELECT * FROM {{ ref('bronze_bookings') }}
),

listings AS (
    SELECT * FROM {{ ref('bronze_listings') }}
),

hosts AS (
    SELECT * FROM {{ ref('bronze_hosts') }}
)

-- ---------- BOOKINGS ----------
SELECT 'BOOKINGS_DUPLICATE_BOOKING_ID' AS CHECK_NAME, BOOKING_ID::STRING AS RECORD_ID
FROM bookings
GROUP BY BOOKING_ID
HAVING COUNT(*) > 1

UNION ALL
SELECT 'BOOKINGS_MISSING_KEY', BOOKING_ID::STRING
FROM bookings
WHERE BOOKING_ID IS NULL OR LISTING_ID IS NULL

UNION ALL
SELECT 'BOOKINGS_INVALID_NIGHTS', BOOKING_ID::STRING
FROM bookings
WHERE TRY_TO_DECIMAL(NIGHTS_BOOKED::STRING, 18, 2) IS NULL
   OR TRY_TO_DECIMAL(NIGHTS_BOOKED::STRING, 18, 2) <= 0

UNION ALL
SELECT 'BOOKINGS_INVALID_AMOUNT', BOOKING_ID::STRING
FROM bookings
WHERE TRY_TO_DECIMAL(BOOKING_AMOUNT::STRING, 18, 2) IS NULL
   OR TRY_TO_DECIMAL(BOOKING_AMOUNT::STRING, 18, 2) < 0

UNION ALL
SELECT 'BOOKINGS_NEGATIVE_FEE', BOOKING_ID::STRING
FROM bookings
WHERE TRY_TO_DECIMAL(CLEANING_FEE::STRING, 18, 2) < 0
   OR TRY_TO_DECIMAL(SERVICE_FEE::STRING, 18, 2) < 0

UNION ALL
SELECT 'BOOKINGS_MISSING_STATUS', BOOKING_ID::STRING
FROM bookings
WHERE BOOKING_STATUS IS NULL OR TRIM(BOOKING_STATUS::STRING) = ''

-- ---------- LISTINGS ----------
UNION ALL
SELECT 'LISTINGS_DUPLICATE_LISTING_ID', LISTING_ID::STRING
FROM listings
GROUP BY LISTING_ID
HAVING COUNT(*) > 1

UNION ALL
SELECT 'LISTINGS_MISSING_KEY', LISTING_ID::STRING
FROM listings
WHERE LISTING_ID IS NULL OR HOST_ID IS NULL

UNION ALL
SELECT 'LISTINGS_INVALID_PRICE', LISTING_ID::STRING
FROM listings
WHERE TRY_TO_DECIMAL(PRICE_PER_NIGHT::STRING, 18, 2) IS NULL
   OR TRY_TO_DECIMAL(PRICE_PER_NIGHT::STRING, 18, 2) <= 0

UNION ALL
SELECT 'LISTINGS_INVALID_CAPACITY', LISTING_ID::STRING
FROM listings
WHERE TRY_TO_DECIMAL(ACCOMMODATES::STRING, 18, 2) IS NULL
   OR TRY_TO_DECIMAL(ACCOMMODATES::STRING, 18, 2) <= 0

-- ---------- HOSTS ----------
UNION ALL
SELECT 'HOSTS_DUPLICATE_HOST_ID', HOST_ID::STRING
FROM hosts
GROUP BY HOST_ID
HAVING COUNT(*) > 1

UNION ALL
SELECT 'HOSTS_MISSING_HOST_ID', HOST_ID::STRING
FROM hosts
WHERE HOST_ID IS NULL

UNION ALL
SELECT 'HOSTS_INVALID_RESPONSE_RATE', HOST_ID::STRING
FROM hosts
WHERE TRY_TO_DECIMAL(REPLACE(TO_VARCHAR(RESPONSE_RATE), '%', ''), 18, 2) < 0
   OR TRY_TO_DECIMAL(REPLACE(TO_VARCHAR(RESPONSE_RATE), '%', ''), 18, 2) > 100

-- ---------- RELATIONSHIPS (orphans) ----------
UNION ALL
SELECT 'BOOKINGS_ORPHAN_LISTING_ID', b.BOOKING_ID::STRING
FROM bookings AS b
LEFT JOIN listings AS l ON b.LISTING_ID = l.LISTING_ID
WHERE b.LISTING_ID IS NOT NULL AND l.LISTING_ID IS NULL

UNION ALL
SELECT 'LISTINGS_ORPHAN_HOST_ID', l.LISTING_ID::STRING
FROM listings AS l
LEFT JOIN hosts AS h ON l.HOST_ID = h.HOST_ID
WHERE l.HOST_ID IS NOT NULL AND h.HOST_ID IS NULL